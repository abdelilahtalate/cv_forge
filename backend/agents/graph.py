from typing import TypedDict, Dict, Any, List
from langgraph.graph import StateGraph, END
from sqlalchemy.orm import Session
from uuid import UUID

from agents.orechestrator.orechestrator import orchestrator
from agents.retreive_data.retreval import data_retriever
from agents.latex.compiler import latex_compiler
from agents.latex.generator import latex_generator
from app.services.cv_service import cv_service
from app.services.extractor_service import extractor_service
from app.services.llm_service import llm_service
from app.models.message import Message
from typing import Optional
# 1. Define the State
class AgentState(TypedDict):
    user_id: str
    conversation_id: str
    user_input: str
    db: Session
    intent: str
    response: str
    pdf_url: Optional[str]
    intermediate_data: Dict[str, Any]

# 2. Define the Nodes
def orchestrator_node(state: AgentState):
    """Classifies the user intent."""
    print(f"--- ORCHESTRATOR NODE ---")
    intent = orchestrator.classify(state["user_input"])
    return {"intent": intent}

def extractor_node(state: AgentState):
    """Extracts information and saves to DB if intent involves storing."""
    print(f"--- EXTRACTOR NODE ---")
    sync_result = extractor_service.sync_user_profile(
        user_id=state["user_id"],
        user_input=state["user_input"],
        db=state["db"]
    )
    return {"intermediate_data": sync_result}

def retriever_node(state: AgentState):
    """Retrieves user data and generates a fluent summary."""
    print(f"--- RETRIEVER NODE ---")
    summary = data_retriever.get_user_summary(
        user_id=state["user_id"],
        db=state["db"],
        user_query=state["user_input"]
    )
    
    return {"response": summary}

def latex_node(state: AgentState):
    """Generates a LaTeX CV and compiles it to PDF."""
    print(f"--- LATEX NODE ---")
    try:
        # 1. Fetch full user data
        data = cv_service.get_full_user_data(state["user_id"], state["db"])
        
        # 2. Generate LaTeX code
        tex_content = latex_generator.generate(data, "modern_cv.tex")
        
        # 3. Compile to PDF
        pdf_filename = f"CV_{data['profile']['full_name'].replace(' ', '_')}"
        pdf_path = latex_compiler.compile(tex_content, pdf_filename)
        
        # Construct public URL using the chat/view endpoint
        public_url = f"http://localhost:8000/api/v1/chat/view/{pdf_filename}.pdf"
        
        response_text = f"I have successfully generated your LaTeX CV! Click the button below to preview it."
        return {"response": response_text, "pdf_url": public_url}
    except Exception as e:
        print(f"Latex Node Error: {str(e)}")
        return {"response": f"I attempted to generate your LaTeX CV but encountered an error: {str(e)}"}

def responder_node(state: AgentState):
    """Generates the final response and saves to DB."""
    print(f"--- RESPONDER NODE ---")
    db = state["db"]
    # Generate response based on intent
    if state["intent"] == "store":
        response_text = "I've successfully updated your profile with the information provided."
    elif state["intent"] == "both":
        response_text = "I've saved your information and updated your profile accordingly."
    elif state["intent"] == "latex":
        response_text = state.get("response") or "I couldn't find any information for your profile."
    elif state["intent"] == "retrieve":
        # If response already generated by retriever node, use it
        response_text = state.get("response") or "I couldn't find any information for your profile."
    else:
        # Fallback to the general LLM service
        response_text = llm_service.generate_response(state["user_input"])

    # Save Assistant Message to DB
    assistant_msg = Message(
        conversation_id=UUID(state["conversation_id"]) if isinstance(state["conversation_id"], str) else state["conversation_id"],
        role="assistant",
        content=response_text,
        pdf_url=state.get("pdf_url")
    )
    db.add(assistant_msg)
    db.commit()

    return {"response": response_text}

# 3. Define the routing logic
def route_after_orchestrator(state: AgentState):
    if state["intent"] in ["store", "both"]:
        return "extractor"
    elif state["intent"] == "retrieve":
        return "retriever"
    elif state["intent"] == "latex":
        return "latex"
    return "responder"

# 4. Build the Graph
workflow = StateGraph(AgentState)

workflow.add_node("orchestrator", orchestrator_node)
workflow.add_node("extractor", extractor_node)
workflow.add_node("retriever", retriever_node)
workflow.add_node("latex", latex_node)
workflow.add_node("responder", responder_node)

workflow.set_entry_point("orchestrator")

workflow.add_conditional_edges(
    "orchestrator",
    route_after_orchestrator,
    {
        "extractor": "extractor",
        "retriever": "retriever",
        "latex": "latex",
        "responder": "responder"
    }
)

workflow.add_edge("extractor", "responder")
workflow.add_edge("retriever", "responder")
workflow.add_edge("latex", "responder")
workflow.add_edge("responder", END)

# 5. Compile the Graph
compiled_graph = workflow.compile()
