import os
import subprocess
import shutil
import tempfile
from pathlib import Path

class LatexCompiler:
    def __init__(self, output_dir: str = None):
        if output_dir is None:
            # Default to exports folder in the backend root
            self.output_dir = Path(__file__).parent.parent.parent / "exports"
        else:
            self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def compile(self, tex_content: str, filename: str) -> str:
        """
        Compiles LaTeX content into a PDF.
        Returns the path to the generated PDF.
        """
        # Ensure filenames don't have extension
        base_name = filename.replace(".pdf", "").replace(".tex", "")
        
        # Create a temporary directory for compilation to avoid cluttering workers
        with tempfile.TemporaryDirectory() as tmp_dir:
            tmp_path = Path(tmp_dir)
            tex_file = tmp_path / f"{base_name}.tex"
            
            # 1. Write the .tex file
            with open(tex_file, "w", encoding="utf-8") as f:
                f.write(tex_content)
            
            # 2. Run pdflatex
            # We run it twice to ensure references and table of contents (if any) are resolved
            try:
                for _ in range(2):
                    process = subprocess.run(
                        ["pdflatex", "-interaction=nonstopmode", f"{base_name}.tex"],
                        cwd=tmp_dir,
                        stdout=subprocess.PIPE,
                        stderr=subprocess.PIPE,
                        text=True,
                        timeout=30 # Prevent hangs
                    )
                
                if process.returncode != 0:
                    print(f"LaTeX Error: {process.stdout}")
                    raise Exception(f"LaTeX compilation failed: {process.stdout[:500]}")

                # 3. Move the resulting PDF to the exports folder
                pdf_file = tmp_path / f"{base_name}.pdf"
                if not pdf_file.exists():
                    raise Exception("PDF file was not generated by pdflatex.")
                
                final_path = self.output_dir / f"{base_name}.pdf"
                shutil.copy(pdf_file, final_path)
                
                return str(final_path)

            except subprocess.TimeoutExpired:
                raise Exception("LaTeX compilation timed out.")
            except Exception as e:
                raise Exception(f"Compiler Error: {str(e)}")

# Singleton instance
latex_compiler = LatexCompiler()
